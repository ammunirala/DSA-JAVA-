package Arrays;

public class InitialisationOfArrays {
    public static void main(String[] args){
        int[] arr = {1,5,8,5,45};
        System.out.println(arr[0]); // here output is 1
        //you can update also
        arr[0] = 10;
        System.out.println(arr[0]); // now the output will be 10

    }
}
